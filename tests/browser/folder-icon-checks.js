const tick = () => new Promise(resolve => setTimeout(resolve, 50));
const section = key => [...document.querySelectorAll('section[data-section-key]')].find(el => el.dataset.sectionKey === key);
const button = (root, text) => [...root.querySelectorAll('button')].find(el => el.textContent.trim() === text);
const rows = el => el.querySelectorAll('[data-prompt-id]').length;
const icon = el => el.querySelector('header svg path').getAttribute('d');

export async function runFolderIconChecks() {
  let assertions = 0;
  const check = (value, message) => { if (!value) throw new Error(message); assertions++; };
  const fixture = window.managerFixture;
  const calls = () => fixture.callsFor('set_folder_appearance').length;
  const notes = section('Note organization');
  const title = notes.querySelector('[data-folder-title] .truncate');
  check(getComputedStyle(title).fontSize === '13px' && getComputedStyle(title).fontWeight === '400', 'title typography');
  check(getComputedStyle(title).textTransform === 'none' && title.textContent.trim() === 'Note organization', 'title original case');
  const openPath = icon(notes);
  notes.querySelector('[data-folder-title]').click(); await tick();
  check(icon(notes) !== openPath, 'folder has closed/open states');
  notes.querySelector('[data-folder-title]').click(); await tick();
  check(icon(notes) === openPath, 'folder reopens');
  const more = button(notes, '展开显示');
  const firstTitle = notes.querySelector('[data-prompt-id] button');
  check(Math.abs(more.getBoundingClientRect().left - firstTitle.getBoundingClientRect().left) < 2, 'show more aligns with prompt title');
  check(rows(notes) === 5, 'initial five rows');
  more.click(); await tick();
  check(rows(notes) === 10, 'more adds five rows');
  const collapse = button(notes, '收起列表');
  const nextMore = button(notes, '展开显示');
  check(Math.abs(collapse.getBoundingClientRect().top - nextMore.getBoundingClientRect().top) < 1, 'more and collapse share one line');
  while (button(notes, '展开显示')) { button(notes, '展开显示').click(); await tick(); }
  check(rows(notes) === 30 && !!button(notes, '收起列表'), 'all rows leave only collapse');
  button(notes, '收起列表').click(); await tick();
  check(rows(notes) === 5 && !button(notes, '收起列表'), 'collapse restores initial five');
  const body = document.querySelector('main textarea');
  const originalBody = body.value;
  body.value = 'Unsaved icon test draft'; body.dispatchEvent(new Event('input', { bubbles: true })); await tick();
  const editorTitle = document.querySelector('main input[placeholder]').value;
  async function open(key) {
    const header = section(key).querySelector('header');
    header.scrollIntoView({ block: 'nearest' }); await tick();
    const rect = header.getBoundingClientRect();
    header.dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, cancelable: true, clientX: rect.left + 24, clientY: rect.top + 10 })); await tick();
    const menu = document.querySelector('[role="menu"]');
    check(!!button(menu, '更改图标'), 'section offers icon action');
    button(menu, '更改图标').click(); await tick();
    return document.querySelector('[data-folder-icon-picker]');
  }
  let picker = await open('Note organization');
  check(picker.querySelectorAll('[data-icon-id]').length === 40, 'forty icon choices');
  check(picker.querySelectorAll('[aria-label="图标颜色"] button').length === 8, 'eight swatches');
  check(document.querySelector('[data-manager-sidebar]').closest('[inert]') !== null, 'background is inert');
  const beforeCancel = calls();
  picker.querySelector('[data-icon-id="book"]').click();
  picker.querySelector('button[aria-label="紫色"]').click();
  button(picker, '取消').click(); await tick();
  check(calls() === beforeCancel && icon(notes) === openPath, 'cancel does not write or change icon');
  picker = await open('Note organization');
  picker.querySelector('[data-icon-id="book"]').click();
  picker.querySelector('button[aria-label="紫色"]').click();
  button(picker, '完成').click(); await tick();
  check(calls() === beforeCancel + 1 && !document.querySelector('[data-folder-icon-picker]'), 'done submits once and closes');
  check(icon(notes) !== openPath && notes.querySelector('header svg').style.color === 'rgb(145, 70, 255)', 'chosen shape and color render');
  check(body.value === 'Unsaved icon test draft' && document.querySelector('main input[placeholder]').value === editorTitle, 'icon editing preserves editor and draft');
  const invoke = window.__TAURI__.core.invoke;
  window.__TAURI__.core.invoke = async (command, args) => { if (command === 'set_folder_appearance') throw 'injected'; return invoke(command, args); };
  picker = await open('Note organization');
  button(picker, '恢复默认').click();
  button(picker, '完成').click(); await tick();
  check(!!document.querySelector('[data-folder-icon-picker] [role="alert"]'), 'failed save retains picker and reports error');
  check(icon(notes) !== openPath, 'failed save preserves saved appearance');
  window.__TAURI__.core.invoke = invoke;
  button(picker, '取消').click(); await tick();
  picker = await open('\0pinned');
  check(picker.querySelector('[data-icon-id="pin"]').getAttribute('aria-pressed') === 'true', 'pinned default pin');
  picker.querySelector('[data-icon-id="star"]').click(); button(picker, '完成').click(); await tick();
  picker = await open('');
  check(picker.querySelector('[data-icon-id="folder"]').getAttribute('aria-pressed') === 'true', 'uncategorized default folder');
  picker.querySelector('[data-icon-id="heart"]').click(); button(picker, '完成').click(); await tick();
  picker = await open('Note organization');
  button(picker, '恢复默认').click(); button(picker, '完成').click(); await tick();
  check(icon(notes) === openPath, 'restore default commits default shape/color');
  body.value = originalBody; body.dispatchEvent(new Event('input', { bubbles: true })); await tick();
  check(fixture.state.alerts.length === 0, 'no unexpected alerts');
  return { group: 'folder-icons', assertions };
}
